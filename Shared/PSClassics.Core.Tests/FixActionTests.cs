using PS_Classics_fPKG_Builder;
using Xunit;

namespace PSClassics.Tests;

public class FixActionTests
{
    [Theory]
    [InlineData("Wine was not found. Install it.", FixAction.WineSetup)]
    [InlineData("msvcr90.dll is missing", FixAction.WineSetup)]
    [InlineData("There is not enough space on the disk", FixAction.TryAgain)]
    [InlineData("Access to the path 'C:/x' is denied", FixAction.TryAgain)]
    [InlineData("The .CUE file of disc 1 is missing", FixAction.SelectGame)]
    [InlineData("The GP4 project was not generated by gengp4_patch.exe", FixAction.OpenToolsFolder)]
    [InlineData("The image could not be read", FixAction.ClearImages)]
    [InlineData("Could not find file 'D:/game.bin'", FixAction.SelectGame)]
    [InlineData("something nobody expected", FixAction.None)]
    public void Explain_GivesTheFixOfTheError(string details, FixAction expected)
    {
        var error = ErrorExplainer.Explain(details);

        Assert.Equal(expected, error.Action);
        Assert.Equal(expected == FixAction.None, error.ActionLabel == "");
    }

    [Fact]
    public void EveryFixActionHasAButtonText()
    {
        foreach (var action in Enum.GetValues<FixAction>().Where(a => a != FixAction.None))
            Assert.NotEqual("", FixActions.Label(action));
        Assert.Equal("", FixActions.Label(FixAction.None));
        Assert.Equal(Enum.GetValues<FixAction>().Length - 1, FixActions.AllTexts().Count());
    }

    [Fact]
    public void CheckAlreadyBuilt_WarnsOnlyWhenThePackageOfTheSameGameStillExists()
    {
        using var ws = new TempWorkspace();
        var history = Path.Combine(ws.Root, "history.json");
        var package = ws.Write(@"out\game.pkg", new byte[8]);
        BuildHistory.AddOrUpdate(new HistoryEntry { Platform = "PS1", NPTitle = "SLUS00594", PackagePath = package, Succeeded = true }, history);
        BuildHistory.AddOrUpdate(new HistoryEntry { Platform = "PS2", NPTitle = "SLUS20000", PackagePath = Path.Combine(ws.Root, "gone.pkg"), Succeeded = true }, history);
        BuildHistory.AddOrUpdate(new HistoryEntry { Platform = "PS1", NPTitle = "SLUS00001", PackagePath = package, Succeeded = false }, history);

        var warning = Assert.Single(BuildPreflight.CheckAlreadyBuilt("PS1", "slus00594", history));
        Assert.False(warning.IsError);
        Assert.Contains(package, warning.Message);
        Assert.Empty(BuildPreflight.CheckAlreadyBuilt("PS2", "SLUS00594", history)); // other platform
        Assert.Empty(BuildPreflight.CheckAlreadyBuilt("PS2", "SLUS20000", history));  // the file is gone
        Assert.Empty(BuildPreflight.CheckAlreadyBuilt("PS1", "SLUS00001", history));  // that build failed
        Assert.Empty(BuildPreflight.CheckAlreadyBuilt("PS1", "", history));
    }

    [Fact]
    public void StartNew_IsOnlyOfferedAfterASuccessAndNeverByTheErrorExplainer()
    {
        Assert.NotEqual("", FixActions.Label(FixAction.StartNew));
        Assert.NotEqual(FixAction.StartNew, ErrorExplainer.Explain("something nobody expected").Action);
        Assert.NotEqual(FixAction.StartNew, ErrorExplainer.Explain("The .CUE file of disc 1 is missing").Action);
    }

    [Fact]
    public void Preflight_MissingDiscOffersToSelectTheGame()
    {
        using var ws = new TempWorkspace();
        var issues = BuildPreflight.CheckPS1(new PS1BuildRequest { Title = "T", NPTitle = "SLUS00594", Disc1 = Path.Combine(ws.Root, "missing.bin") }, null);

        Assert.Contains(FixAction.SelectGame, issues.Select(issue => issue.Action)); // (without a Tools folder the first fix is OpenToolsFolder)
    }

    [Fact]
    public void Preflight_MissingImageOffersToClearImages()
    {
        using var ws = new TempWorkspace();
        var disc = ws.Write(@"g\game.bin", new byte[2352]);
        ws.Write(@"g\game.cue", "FILE \"game.bin\" BINARY\r\n  TRACK 01 MODE2/2352\r\n    INDEX 01 00:00:00\r\n");
        var issues = BuildPreflight.CheckPS1(new PS1BuildRequest { Title = "T", NPTitle = "SLUS00594", Disc1 = disc, IconFile = Path.Combine(ws.Root, "gone.png") }, null);

        Assert.Contains(FixAction.ClearImages, issues.Select(issue => issue.Action));
    }

    [Fact]
    public void Preflight_WarningsAndProblemsWithoutFixGiveNoAction()
    {
        var warning = new PreflightIssue { IsError = false, Message = "w", Action = FixAction.SelectGame };
        var plain = new PreflightIssue { IsError = true, Message = "e" };

        Assert.Equal(FixAction.None, BuildPreflight.FirstAction(new[] { warning, plain }));
        Assert.Equal(FixAction.None, BuildPreflight.FirstAction(new List<PreflightIssue>()));
    }
}
